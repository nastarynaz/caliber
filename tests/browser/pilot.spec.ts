  const run = async (action: string, data = {}) => {
    const r = await page.request.post("/api/hub", { headers: { Origin: origin }, data: { action, id, data, expectedRevision: snapshot.state.revision } });
    expect(r.status(), await r.text()).toBe(200); snapshot = await r.json();
  };
  const role = async (value: string) => { expect((await page.request.post("/api/session", { headers: { Origin: origin }, data: { role: value } })).ok()).toBe(true); };
