  await role("engineer"); await run("case.respond", { comment: "Observed during routine inspection" });
  await role("reviewer"); await run("case.assign", { assignedTo: "Demo investigation team" });
  await role("engineer"); await run("case.update", { comment: "Inspection findings appended" });
