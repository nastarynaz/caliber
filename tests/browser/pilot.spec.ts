test("document API enforces lifecycle, ACLs, exact files, and session isolation", async ({ page, browser }) => {
  await page.goto("/login");
  const origin = new URL(page.url()).origin;
  const role = async (value: string) => {
    const r = await page.request.post("/api/session", { headers: { Origin: origin }, data: { role: value } }); expect(r.ok()).toBe(true);
  };
  await role("controller");
  let snapshot = await (await page.request.get("/api/hub")).json();
  const id = snapshot.state.documents[0].id;
  const run = async (action: string, data = {}, status = 200) => {
    const r = await page.request.post("/api/hub", { headers: { Origin: origin }, data: { action, id, data, expectedRevision: snapshot.state.revision } });
    expect(r.status()).toBe(status); if (r.ok()) snapshot = await r.json();
  };
  await run("document.metadata", { title: "Synthetic test metadata", number: "DEMO-TEST", owner: "Test owner", purpose: "Test only", access: "reviewers", equipmentIds: ["EQP-000001", "EQP-000002"] });
  await run("document.submit");
  await run("document.approve", { comment: "Self approval denied" }, 403);
  await role("reviewer"); await run("document.approve", { comment: "Test approval" });
  await role("controller"); await run("document.publish"); await run("document.fail_index"); await run("document.index");
  expect((await page.request.get(`/api/files/${id}`)).status()).toBe(200);
  await role("reader");
  expect((await page.request.get(`/api/files/${id}`)).status()).toBe(404);
  const current = await (await page.request.get("/api/hub")).json();
  expect(current.state.documents.some((d: { id: string }) => d.id === id)).toBe(false);
  const other = await browser.newContext();
  expect((await other.request.get(`${origin}/api/hub`)).status()).toBe(401);
  expect((await other.request.get(`${origin}/api/files/${id}`)).status()).toBe(401);
  await other.close();
  const csrf = await page.request.post("/api/session", { headers: { Origin: "https://untrusted.invalid" }, data: { role: "controller" } });
  expect(csrf.status()).toBe(403);
});

