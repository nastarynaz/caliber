  await run("case.resolve", closure);
  await role("reviewer"); await run("case.return", { comment: "Clarify verification evidence" });
  await role("engineer"); await run("case.resolve", { ...closure, evidence: "Corrected synthetic verification record" });
  await role("reviewer"); await run("case.verify", { comment: "Outcome verified in demo; cause remains unestablished" });
